def roles_for_formation(formation: str) -> List[str]:
    key = normalize_formation_key(formation)
    return list(ROLES_BY_FORMATION.get(key, ROLES_BY_FORMATION["433"]))


def formation_anchor_maps(key: str) -> Dict[str, Tuple[Tuple[float, float], Tuple[float, float]]]:
    return _FORMATIONS.get(key, _FORMATIONS["433"])


def interpolate_anchors(
    role: str,
    phase: float,
    line_height: float = 0.5,
    width: float = 0.5,
    *,
    attacks_high_x: bool = True,
    cb_wide: float = 0.0,
    formation_key: str = "433",
) -> np.ndarray:
    maps = formation_anchor_maps(formation_key)
    d, a = maps.get(role, maps.get("CM", ((0.35, 0.5), (0.55, 0.5))))
    x = (1.0 - phase) * d[0] + phase * a[0]
    y = (1.0 - phase) * d[1] + phase * a[1]
    if role == "CB" and cb_wide > 0:
        y = 0.38 if cb_wide < 0.5 else 0.62
    x += (line_height - 0.5) * 0.14
    y = 0.5 + (y - 0.5) * (0.75 + 0.5 * width)
    p = np.array([float(np.clip(x, 0.04, 0.92)), float(np.clip(y, 0.06, 0.94))], dtype=float)
    if not attacks_high_x:
        p[0] = 1.0 - p[0]
    return p


def mirror_for_away(p_home_frame: np.ndarray) -> np.ndarray:
    return np.array([1.0 - p_home_frame[0], p_home_frame[1]], dtype=float)
